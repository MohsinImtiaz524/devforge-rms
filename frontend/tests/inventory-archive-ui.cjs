const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({headless:true,channel:process.env.ARCHIVE_BROWSER_CHANNEL || 'chrome'});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors = [], entries = [], requests = [];
  let rejectNextArchive = false;
  page.on('pageerror',error=>errors.push(error.message));
  const permissions = ['inventory_archive.view','inventory_archive.archive','inventory_archive.restore'];
  await page.route('**/api/**',async route => {
    const req = route.request(), url = new URL(req.url());
    if (!url.pathname.startsWith('/api/')) return route.continue();
    requests.push(url.pathname);
    let data;
    if (url.pathname === '/api/auth/me') data = {user:{id:1,name:'Archive tester',shop_id:1,shop_name:'Test Restaurant',role:'staff',permissions,shop_currency:'PKR'}};
    else if (url.pathname === '/api/raw-stock') data = {items:[{id:1,name:'Flour',unit:'kg',current_stock:20,min_stock_level:1,batches:[]}],pagination:{page:1,total_pages:1,total:1,page_size:25}};
    else if (url.pathname === '/api/products') data = {items:[{id:2,name:'Coffee',product_type:'stock_based',stock:8,stock_variants:[{id:3,name:'Regular',stock:8,buying_price:2,selling_price:4,min_stock_level:1}]}],pagination:{page:1,total_pages:1,total:1,page_size:25}};
    else if (url.pathname.endsWith('/targets')) data = [{id:1,name:'Flour',unit:'kg',available:20}];
    else if (req.method() === 'POST' && url.pathname.endsWith('/restore')) {
      const entry = entries.find(e=>String(e.id) === url.pathname.split('/').at(-2));
      const body=req.postDataJSON(); entry.restored_at=new Date().toISOString();entry.restore_reason=body.reason;entry.restored_by='Archive tester';entry.restore_before={current_stock:18};entry.restore_after={current_stock:20};data={ok:true};
    } else if (req.method() === 'POST') {
      if (rejectNextArchive) {rejectNextArchive=false;await route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({error:'This product has an unfinished order.'})});return;}
      const body=req.postDataJSON(); assert.ok(body.requestId);assert.ok(body.reason.trim().length>=3);
      data={id:entries.length+1,...body,entity_id:body.entityId,name:'Flour',unit:'kg',quantity:body.quantity||20,actor_id:1,actor_name:'Archive tester',created_at:new Date().toISOString(),snapshot:{before:{current_stock:20},after:{current_stock:body.kind==='quantity'?18:20}},allocations:body.kind==='quantity'?[{source:'batch',id:1,quantity:2,unitCost:100}]:[]};entries.push(data);
    } else if (url.pathname === '/api/inventory-archives') {
      const items=entries.filter(e=>e.kind===url.searchParams.get('kind') && (url.searchParams.get('status')==='all' || Boolean(e.restored_at)===(url.searchParams.get('status')==='restored')));
      data={items,total:items.length,page:1,pages:1};
    } else throw new Error(`Unexpected request ${url.pathname}`);
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(data)});
  });
  try {
    await page.goto('http://127.0.0.1:5179/app/inventory?view=archive');
    await page.getByRole('heading',{name:'Inventory Archive',exact:true}).waitFor();
    await page.getByRole('button',{name:'Archive an item',exact:true}).click();
    await page.getByLabel('Item',{exact:true}).selectOption('1');
    await page.getByLabel('Reason (required)').fill('Product temporarily held');
    await page.getByRole('dialog').getByRole('button',{name:'Archive',exact:true}).click();
    await page.getByText('Product temporarily held').waitFor();
    await page.getByRole('button',{name:'Archived stock',exact:true}).click();
    await page.getByRole('button',{name:'Archive a quantity',exact:true}).click();
    await page.getByLabel('Item',{exact:true}).selectOption('1');
    await page.getByLabel('Quantity to archive').fill('2');
    await page.getByLabel('Reason (required)').fill('Stock under inspection');
    await page.getByRole('dialog').getByRole('button',{name:'Archive',exact:true}).click();
    await page.getByText('Stock under inspection').waitFor();
    await page.getByText('Audit details and original costs',{exact:true}).click();
    await page.screenshot({path:path.resolve(__dirname,'../../tmp/archive-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Restore',exact:true}).click();
    await page.getByLabel('Reason (required)').fill('Inspection completed');
    await page.screenshot({path:path.resolve(__dirname,'../../tmp/archive-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Confirm restore'}).click();
    await Promise.all([page.waitForResponse(response => response.url().includes('status=restored')),page.getByLabel('Status').selectOption('restored')]);
    await page.getByText(/Inspection completed/).waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth),true);
    await page.evaluate(()=>document.documentElement.classList.add('dark'));
    await page.screenshot({path:path.resolve(__dirname,'../../tmp/archive-mobile-dark.png'),fullPage:true});
    assert.equal(entries.length,2);assert.equal(entries[1].quantity,2);assert.ok(entries[1].restored_at);
    assert.equal(requests.some(p=>p==='/api/users'||p==='/api/printers'||p==='/api/products'||p==='/api/raw-stock'),false);
    assert.deepEqual(errors,[]);
    permissions.splice(0,permissions.length,'inventory_archive.view');
    await page.reload(); await page.getByRole('heading',{name:'Inventory Archive',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:/Archive an item|Archive a quantity|^Restore$/}).count(),0);
    permissions.push('inventory_archive.archive','raw_stock.view','products.view');
    await page.goto('http://127.0.0.1:5179/app/inventory');
    await page.getByRole('button',{name:'Archive ingredient Flour',exact:true}).click();
    assert.equal(new URL(page.url()).searchParams.get('view'),null);
    await page.getByRole('heading',{name:'Archive Flour',exact:true}).waitFor();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(new URL(page.url()).searchParams.get('view'),null);
    await page.getByRole('button',{name:'Archive ingredient Flour',exact:true}).click();
    await page.getByLabel('Archive scope',{exact:true}).selectOption('quantity');
    await page.getByLabel('Quantity to archive').fill('3');
    await page.getByLabel('Reason (required)').fill('Archive quantity from ingredient row');
    await page.screenshot({path:path.resolve(__dirname,'../../tmp/archive-form-mobile.png'),fullPage:true});
    await page.getByRole('dialog').getByRole('button',{name:'Archive',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.equal(new URL(page.url()).searchParams.get('view'),null);
    assert.equal(entries[2].entity,'ingredient');assert.equal(entries[2].entityId,1);assert.equal(entries[2].quantity,3);
    await page.getByRole('button',{name:'Archive product Coffee',exact:true}).click();
    await page.getByRole('heading',{name:'Archive Coffee',exact:true}).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(),0);
    await page.getByRole('button',{name:'Archive product Coffee',exact:true}).click();
    await page.getByLabel('Reason (required)').fill('Product held after review');
    await page.getByLabel('Product or variant',{exact:true}).selectOption('3');
    rejectNextArchive=true;
    await page.getByRole('dialog').getByRole('button',{name:'Archive',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'unfinished order'}).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('view'),null);
    assert.equal(await page.getByLabel('Reason (required)').inputValue(),'Product held after review');
    await page.getByLabel('Archive scope',{exact:true}).selectOption('quantity');
    await page.getByLabel('Quantity to archive').fill('2');
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:path.resolve(__dirname,'../../tmp/archive-form-desktop.png'),fullPage:true});
    await page.getByRole('dialog').getByRole('button',{name:'Archive',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.equal(new URL(page.url()).searchParams.get('view'),null);
    assert.equal(entries[3].entity,'variant');assert.equal(entries[3].entityId,3);assert.equal(entries[3].quantity,2);
    permissions.splice(0,permissions.length,'raw_stock.view','products.view');
    await page.goto('http://127.0.0.1:5179/app/inventory');
    await page.getByRole('heading',{name:'Raw Ingredients',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:/Archive ingredient|Archive product/}).count(),0);
    assert.deepEqual(errors,[]);
    console.log('PASS: archive workflows, ingredient/product row selection, quantity from row, cancel, permissions, desktop/mobile and dark mode');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
