async function ensureInventoryArchiveSchema(db) {
  await db.raw(`
    CREATE TABLE IF NOT EXISTS inventory_archives (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      shop_id INTEGER NOT NULL REFERENCES shops(id),
      kind TEXT NOT NULL CHECK (kind IN ('item','quantity')),
      entity TEXT NOT NULL CHECK (entity IN ('ingredient','product','variant')),
      entity_id INTEGER NOT NULL,
      product_id INTEGER,
      name TEXT NOT NULL,
      unit TEXT NOT NULL,
      quantity NUMERIC(18,3) NOT NULL CHECK (quantity >= 0),
      reason TEXT NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 1000),
      actor_id INTEGER NOT NULL,
      actor_name TEXT NOT NULL,
      snapshot JSONB NOT NULL,
      allocations JSONB NOT NULL DEFAULT '[]',
      request_id UUID NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE(shop_id,request_id)
    );
    CREATE INDEX IF NOT EXISTS inventory_archives_shop_date ON inventory_archives(shop_id,id DESC);
    CREATE INDEX IF NOT EXISTS inventory_archives_shop_product ON inventory_archives(shop_id,product_id);
    CREATE TABLE IF NOT EXISTS inventory_archive_restores (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      shop_id INTEGER NOT NULL REFERENCES shops(id),
      archive_id BIGINT NOT NULL UNIQUE REFERENCES inventory_archives(id),
      reason TEXT NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 1000),
      actor_id INTEGER NOT NULL,
      actor_name TEXT NOT NULL,
      before_state JSONB NOT NULL,
      after_state JSONB NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE INDEX IF NOT EXISTS inventory_archive_restores_shop ON inventory_archive_restores(shop_id,archive_id);
    CREATE OR REPLACE FUNCTION inventory_archive_immutable() RETURNS trigger AS $$
    BEGIN RAISE EXCEPTION 'Inventory archive history is immutable'; END;
    $$ LANGUAGE plpgsql;
    DROP TRIGGER IF EXISTS inventory_archives_immutable ON inventory_archives;
    CREATE TRIGGER inventory_archives_immutable BEFORE UPDATE OR DELETE ON inventory_archives
      FOR EACH ROW EXECUTE FUNCTION inventory_archive_immutable();
    DROP TRIGGER IF EXISTS inventory_archive_restores_immutable ON inventory_archive_restores;
    CREATE TRIGGER inventory_archive_restores_immutable BEFORE UPDATE OR DELETE ON inventory_archive_restores
      FOR EACH ROW EXECUTE FUNCTION inventory_archive_immutable();
  `);
}
module.exports = { ensureInventoryArchiveSchema };
