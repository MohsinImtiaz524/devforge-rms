const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const knex = require('knex');
const { archiveInput } = require('../src/modules/inventory/archive.schema');
const { createArchiveService } = require('../src/modules/inventory/archive.service');
const { ensureInventoryArchiveSchema } = require('../src/modules/inventory/archive.migration');

const request = (entity,entityId,kind='item',quantity) => ({ entity,entityId,kind,reason:'Stock held for inspection',requestId:crypto.randomUUID(),...(quantity === undefined ? {} : {quantity}) });
test('archive input rejects missing reasons, invalid quantities and untrusted scope', () => {
  const valid = request('ingredient',1,'quantity',0.125);
  assert.equal(archiveInput.parse(valid).quantity,0.125);
  for (const invalid of [{...valid,reason:' '},{...valid,quantity:0},{...valid,quantity:-1},{...valid,quantity:0.0001},{...valid,quantity:1.0001},{...valid,shop_id:2},{...valid,requestId:'retry'}]) {
    assert.equal(archiveInput.safeParse(invalid).success,false);
  }
});

// Explicit disposable test URL only. Never reads DATABASE_URL or production .env.
test('PostgreSQL archive transactions, isolation, restoration, costing and immutable audit', { skip:!process.env.ARCHIVE_TEST_DATABASE_URL }, async t => {
  const schema = 'archive_test_'+crypto.randomBytes(8).toString('hex');
  const admin = knex({client:'pg',connection:process.env.ARCHIVE_TEST_DATABASE_URL,pool:{min:0,max:1}});
  let db;
  try {
    await admin.raw('CREATE SCHEMA ??',[schema]);
    db = knex({client:'pg',connection:process.env.ARCHIVE_TEST_DATABASE_URL,searchPath:[schema],pool:{min:0,max:5}});
    await db.raw(`
      CREATE TABLE shops(id integer primary key,product_count integer default 1);
      CREATE TABLE raw_stocks(id integer primary key,shop_id integer,name text,unit text,current_stock double precision,is_deleted integer default 0);
      CREATE TABLE raw_stock_batches(id integer generated by default as identity primary key,shop_id integer,raw_stock_id integer,buying_price double precision,quantity double precision,expiry_date date,created_at timestamptz default now());
      CREATE TABLE products(id integer primary key,shop_id integer,name text,product_type text default 'stock_based',stock double precision,is_deleted integer default 0,variants_config jsonb default '[]',addons_config jsonb default '[]');
      CREATE TABLE product_stock_variants(id integer primary key,shop_id integer,product_id integer,name text,stock double precision,buying_price double precision,is_active boolean default true,is_on_menu boolean default true);
      CREATE TABLE recipes(id integer primary key,shop_id integer);
      CREATE TABLE recipe_ingredients(id integer primary key,recipe_id integer,raw_stock_id integer);
      CREATE TABLE menu_addons(id integer primary key,shop_id integer,is_active integer default 1,raw_stock_id integer);
      CREATE TABLE menu_addon_ingredients(menu_addon_id integer,raw_stock_id integer);
      CREATE TABLE product_compositions(parent_product_id integer,component_product_id integer);
      CREATE TABLE sales(id integer primary key,shop_id integer,order_status text);
      CREATE TABLE sale_items(sale_id integer,product_id integer,stock_variant_id integer);
      INSERT INTO shops(id) VALUES(1),(2);
      INSERT INTO raw_stocks VALUES(1,1,'Flour','kg',10,0),(2,2,'Private','kg',10,0);
      INSERT INTO raw_stock_batches(shop_id,raw_stock_id,buying_price,quantity) VALUES(1,1,2,2),(1,1,4,8),(2,2,10,10);
      INSERT INTO products(id,shop_id,name,stock) VALUES(1,1,'Coffee',20),(2,2,'Other shop',20);
      INSERT INTO product_stock_variants(id,shop_id,product_id,name,stock,buying_price) VALUES(1,1,1,'Small',10,3),(2,1,1,'Large',10,5),(3,2,2,'Secret',20,5);
    `);
    await ensureInventoryArchiveSchema(db);
    await ensureInventoryArchiveSchema(db);
    const service = createArchiveService(db), user = {id:7,shop_id:1,name:'Inventory Operator'};
    const stock = async () => Number((await db('raw_stocks').where({id:1}).first()).current_stock);
    await db('raw_stock_batches').where({id:1}).update({expiry_date:'2030-06-10'});
    await t.test('FIFO quantity archive is idempotent and audit captures actor and balances', async () => {
      const input = request('ingredient',1,'quantity',3);
      const [a,b] = await Promise.all([service.archive(user,input),service.archive(user,input)]);
      assert.equal(a.id,b.id); assert.equal(await stock(),7);
      assert.deepEqual(a.allocations.map(x=>x.quantity),[2,1]);
      assert.deepEqual(a.allocations.map(x=>Number(x.unitCost)),[2,4]);
      assert.equal(a.actor_name,user.name); assert.equal(a.snapshot.before.current_stock,10); assert.equal(a.snapshot.after.current_stock,7);
      assert.equal(a.allocations[0].expiry_date,'2030-06-10');
      await assert.rejects(service.archive(user,{...input,quantity:4}),/already used/);
      await db('raw_stock_batches').where({id:1}).update({buying_price:99});
      await Promise.all([service.restore(user,a.id,{reason:'Inspection completed'}),service.restore(user,a.id,{reason:'Retry after timeout'})]);
      assert.equal(await stock(),10);
      const batches = await db('raw_stock_batches').where({shop_id:1,raw_stock_id:1});
      assert.equal(batches.reduce((sum,b)=>sum+b.quantity*b.buying_price,0),36);
      const replacement = await db('raw_stock_batches').where({shop_id:1,raw_stock_id:1,buying_price:2}).select(db.raw("to_char(expiry_date,'YYYY-MM-DD') as expiry")).first();
      assert.equal(replacement.expiry,'2030-06-10');
      assert.equal(Number((await db('inventory_archive_restores').count('* as n').first()).n),1);
    });
    await t.test('wrong-shop records, excessive quantity and missing tenant are rejected', async () => {
      await assert.rejects(service.archive(user,request('ingredient',2)),/not found/);
      await assert.rejects(service.archive(user,request('variant',3)),/not found/);
      await assert.rejects(service.archive(user,request('ingredient',1,'quantity',11)),/exceeds/);
      await assert.rejects(service.list({id:7}),/Select a restaurant/);
      assert.equal(await stock(),10);
    });
    await t.test('whole ingredient archive and restore preserves balances', async () => {
      const a = await service.archive(user,request('ingredient',1));
      assert.equal((await db('raw_stocks').where({id:1}).first()).is_deleted,1);
      await assert.rejects(service.archive(user,request('ingredient',1)),/already archived/);
      await service.restore(user,a.id,{reason:'Ingredient approved'});
      assert.equal(await stock(),10);
    });
    await t.test('active recipe and JSON menu links block ingredient item archival', async () => {
      await db('recipes').insert({id:1,shop_id:1}); await db('recipe_ingredients').insert({id:1,recipe_id:1,raw_stock_id:1});
      await assert.rejects(service.archive(user,request('ingredient',1)),/linked to a recipe/);
      await db('recipe_ingredients').delete();
      await db('products').where({id:1}).update({variants_config:JSON.stringify([{ingredients:[{raw_stock_id:1}]}])});
      await assert.rejects(service.archive(user,request('ingredient',1)),/active menu/);
      await db('products').where({id:1}).update({variants_config:'[]'});
    });
    await t.test('product quantities allocate variants and restore original value after cost changes', async () => {
      const a = await service.archive(user,request('product',1,'quantity',12));
      assert.deepEqual(a.allocations.map(x=>x.quantity),[10,2]);
      assert.equal((await db('products').where({id:1}).first()).stock,8);
      await db('product_stock_variants').where({id:1}).update({buying_price:100});
      await service.restore(user,a.id,{reason:'Return held stock'});
      assert.equal((await db('products').where({id:1}).first()).stock,20);
      assert.equal((await db('product_stock_variants').where({id:1}).first()).buying_price,3);
    });
    await t.test('variant archive removes only its active balance; restore stays off menu', async () => {
      const a = await service.archive(user,request('variant',1));
      assert.equal((await db('products').where({id:1}).first()).stock,10);
      await service.restore(user,a.id,{reason:'Variant available again'});
      const variant = await db('product_stock_variants').where({id:1}).first();
      assert.equal(variant.stock,10); assert.equal(variant.is_active,true); assert.equal(variant.is_on_menu,false);
      assert.equal((await db('products').where({id:1}).first()).stock,20);
    });
    await t.test('unfinished orders block item archive; whole product preserves child state', async () => {
      await db('sales').insert({id:1,shop_id:1,order_status:'pending'}); await db('sale_items').insert({sale_id:1,product_id:1,stock_variant_id:1});
      await assert.rejects(service.archive(user,request('product',1)),/unfinished/);
      await db('sales').where({id:1}).update({order_status:'completed'});
      const a = await service.archive(user,request('product',1));
      assert.equal((await db('products').where({id:1}).first()).is_deleted,1);
      await assert.rejects(service.archive(user,request('variant',1)),/already archived/);
      await service.restore(user,a.id,{reason:'Product available'});
      assert.equal((await db('shops').where({id:1}).first()).product_count,1);
    });
    await t.test('audit history cannot be edited/deleted and restore cannot cross shops', async () => {
      const a = await service.archive(user,request('variant',1,'quantity',1));
      await assert.rejects(service.restore({...user,shop_id:2},a.id,{reason:'Wrong restaurant'}),/not found/);
      await assert.rejects(db('inventory_archives').where({id:a.id}).update({reason:'Rewrite history'}),/immutable/);
      await assert.rejects(db('inventory_archives').where({id:a.id}).delete(),/immutable/);
      await service.restore(user,a.id,{reason:'Restore quantity'});
      await assert.rejects(db('inventory_archive_restores').where({archive_id:a.id}).delete(),/immutable/);
      const list = await service.list(user,{status:'all'});
      assert.ok(list.items.every(x=>x.shop_id===1));
      assert.equal((await service.list({...user,shop_id:2},{status:'all'})).total,0);
    });
    await t.test('concurrent excessive reservations cannot overdraw stock', async () => {
      const results = await Promise.allSettled([service.archive(user,request('ingredient',1,'quantity',6)),service.archive(user,request('ingredient',1,'quantity',6))]);
      assert.equal(results.filter(x=>x.status==='fulfilled').length,1); assert.equal(await stock(),4);
    });
    await t.test('audit failure rolls back the stock movement', async () => {
      await db.raw(`CREATE FUNCTION reject_archive_test() RETURNS trigger AS $$ BEGIN IF NEW.reason='Force rollback' THEN RAISE EXCEPTION 'Simulated audit failure'; END IF; RETURN NEW; END; $$ LANGUAGE plpgsql; CREATE TRIGGER reject_archive_test BEFORE INSERT ON inventory_archives FOR EACH ROW EXECUTE FUNCTION reject_archive_test();`);
      await assert.rejects(service.archive(user,{...request('ingredient',1,'quantity',1),reason:'Force rollback'}),/Simulated audit failure/);
      assert.equal(await stock(),4);
    });
    await t.test('unit changes cannot silently corrupt restored ingredient quantities', async () => {
      const a = await service.archive(user,request('ingredient',1,'quantity',0.5));
      await db('raw_stocks').where({id:1}).update({unit:'grams'});
      await assert.rejects(service.restore(user,a.id,{reason:'Restore in wrong unit'}),/unit changed/);
      assert.equal(await stock(),3.5);
      await db('raw_stocks').where({id:1}).update({unit:'kg'});
      await service.restore(user,a.id,{reason:'Original unit restored'});
      assert.equal(await stock(),4);
    });
    await t.test('HTTP permissions are independent and wrong-shop requests cannot mutate stock', async () => {
      require('express-async-errors');
      const express = require('express');
      const { createArchiveRouter } = require('../src/modules/inventory/archive.routes');
      const { enforceApiPermissions } = require('../authorization/api-policy');
      const { formatErrorResponse } = require('../utils/error-response');
      const app = express(); app.use(express.json());
      app.use((req,res,next) => {
        if (req.headers['x-test-user']) req.session = {user:{...user,shop_id:Number(req.headers['x-test-shop'] || 1)}};
        req.permissions = String(req.headers['x-test-permissions'] || '').split(',').filter(Boolean);
        next();
      });
      app.use(enforceApiPermissions); app.use('/api/inventory-archives',createArchiveRouter(db));
      app.use((error,req,res,next) => { const result=formatErrorResponse(error);res.status(result.status).json(result.body); });
      const server = await new Promise(resolve => {const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
      const base = `http://127.0.0.1:${server.address().port}/api/inventory-archives`;
      const http = (path='',permissions='',body,shop=1) => fetch(base+path,{method:body?'POST':'GET',headers:{'Content-Type':'application/json','x-test-user':'yes','x-test-shop':String(shop),'x-test-permissions':permissions},...(body?{body:JSON.stringify(body)}:{})});
      try {
        assert.equal((await fetch(base)).status,401);
        assert.equal((await http()).status,403);
        const targets = await http('/targets?entity=variant&search=Coffee','inventory_archive.archive');
        assert.equal(targets.status,200); assert.equal((await targets.json()).length,2);
        assert.equal((await http('/targets?entity=ingredient','inventory_archive.view')).status,403);
        assert.equal((await http('','inventory_archive.view',request('ingredient',1,'quantity',0.5))).status,403);
        assert.equal((await http('','inventory_archive.archive',request('ingredient',1),2)).status,404);
        const response = await http('','inventory_archive.archive',request('ingredient',1,'quantity',0.5));
        assert.equal(response.status,201); const entry = await response.json();
        assert.equal((await http(`/${entry.id}/restore`,'inventory_archive.archive',{reason:'Permission test'})).status,403);
        assert.equal((await http(`/${entry.id}/restore`,'inventory_archive.restore',{reason:'Permission test'})).status,200);
        assert.equal((await http('?status=all','inventory_archive.view')).status,200);
        assert.equal(await stock(),4);
      } finally { await new Promise(resolve=>server.close(resolve)); }
    });
  } finally {
    if (db) await db.destroy();
    await admin.raw('DROP SCHEMA IF EXISTS ?? CASCADE',[schema]);
    await admin.destroy();
  }
});
