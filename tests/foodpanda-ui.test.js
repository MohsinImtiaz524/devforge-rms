const test = require('node:test');
const path = require('node:path');
const express = require('express');
const { chromium, expect } = require('../frontend/node_modules/@playwright/test');

test('Foodpanda enable/open/stop flow preserves orders in the shared responsive Moons layout', async () => {
  let enabled = false, activated = false, moonSubscribed = false;
  const user = {id:1,shop_id:1,name:'Restaurant Admin',role:'admin',shop_name:'Test Restaurant',shop_currency:'PKR',shop_type:'restaurant',allowed_order_types:['dine_in','takeaway','delivery'],permissions:['orders.create','orders.view']};
  const app = express();
  app.use(express.json());
  app.get('/api/auth/me', (req,res)=>res.json({user}));
  app.get(['/api/tables','/api/tables/floors','/api/users/assignable','/api/product-categories','/api/shop-settings/discounts','/api/shop-settings/taxes','/api/shop-settings/payment-methods'],(req,res)=>res.json([]));
  app.get('/api/products',(req,res)=>res.json({items:[],pagination:{page:1,total:0,total_pages:1}}));
  app.get('/api/shop-settings/pos',(req,res)=>res.json({pos_direct_variant_searching:false}));
  app.get('/api/order-workload',(req,res)=>res.json({members:[]}));
  app.get('/api/notifications/unread-count',(req,res)=>res.json({count:0}));
  app.get('/api/moons/directory', (req,res)=>res.json({user,can_subscribe:true,items:[{id:1,key:'analytics',name:'Subscribed Analytics',summary:'Your reports',category:'insights',description:'Reports',features:[],artwork:[],subscription:{state:'active'},can_open:true,route:'/app/moons/analytics'},{id:2,key:'website',name:'Website Builder',summary:'A website for your shop',category:'web',description:'Website',features:[],artwork:[],version:1,price:{id:12,monthly_amount_minor:100000,currency:'PKR'},subscription:moonSubscribed?{state:'active'}:null,can_open:true,route:'/app/moons/website'},{id:3,key:'upcoming',name:'Upcoming Moon',summary:'Coming soon',category:'other',description:'Future app',features:[],artwork:[],subscription:null,launch_ready:false,can_open:false}]}));
  app.get('/api/shop-branding', (req,res)=>res.json({logo_url:null}));
  app.get('/api/platform-icons', (req,res)=>res.json([{key:'foodpanda',label:'Foodpanda',image_url:null},{key:'food_panda',label:'Food Panda',image_url:'/api/test-panda.svg'}]));
  app.get('/api/test-panda.svg',(req,res)=>res.type('image/svg+xml').send('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><circle cx="16" cy="16" r="14" fill="#e21b70"/></svg>'));
  app.get('/api/integrations/foodpanda', (req,res)=>res.json({enabled,activated,can_manage:true}));
  app.put('/api/integrations/foodpanda', (req,res)=>{enabled=req.body.enabled;activated=activated||enabled;res.json({enabled,activated})});
  app.get('/api/integrations/foodpanda/orders', (req,res)=>res.json({summary:{total_orders:1,active_orders:1,completed_orders:0,cancelled_orders:0,completed_sales:0},orders:[{id:1,order_number:101,order_source:'foodpanda',order_type:'foodpanda',order_status:'pending',customer_name:'Panda customer',total:1000,created_at:'2026-11-23T12:00:00Z'}],pagination:{page:1,page_size:20,total:1,total_pages:1}}));
  app.post('/api/moons/directory/website/subscribe',(req,res)=>{moonSubscribed=true;res.json({subscription:{state:'active'}})});
  const dist=path.resolve(__dirname,'../frontend/dist');
  app.use('/app',express.static(dist));
  app.get('/app/*',(req,res)=>res.sendFile(path.join(dist,'index.html')));
  const server=app.listen(0);
  await new Promise(resolve=>server.once('listening',resolve));
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    page.setDefaultTimeout(10000);
    const origin='http://127.0.0.1:'+server.address().port;
    await page.goto(origin+'/app/moons');
    await expect(page.getByRole('heading',{name:'A little Moon. A whole new possibility.'})).toBeVisible();
    await expect(page.locator('.market-content')).toHaveCount(0);
    await expect(page.getByRole('tablist')).toHaveCount(0);
    await expect(page.locator('.moons-directory .market-topbar')).toHaveCount(0);
    await expect(page.getByRole('complementary',{name:'Workspace sidebar'}).getByRole('link',{name:'Notifications',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'Open account menu'})).toBeVisible();
    const hero=await page.locator('.market-hero').boundingBox();
    expect(hero.height).toBeGreaterThanOrEqual(930);
    await page.screenshot({path:path.join(process.env.TEMP,'rms-moons-hero-desktop.png'),fullPage:true});
    await page.getByRole('button',{name:'Explore your Moons'}).click();
    await expect(page.getByRole('heading',{name:'Store',exact:true,level:2})).toBeVisible();
    await expect(page.locator('.market-hero')).toHaveCount(0);
    await expect(page.getByRole('button',{name:'View details for Website Builder'})).toBeVisible();
    await expect(page.getByRole('button',{name:'View details for Upcoming Moon'})).toBeVisible();
    await expect(page.getByRole('button',{name:'View details for Subscribed Analytics'})).toHaveCount(0);
    await page.getByRole('navigation',{name:'Moons navigation'}).getByRole('button',{name:'Moons',exact:true}).click();
    await expect(page.getByRole('button',{name:'View details for Subscribed Analytics'})).toBeVisible();
    await expect(page.getByRole('button',{name:'View details for Website Builder'})).toHaveCount(0);
    await page.getByRole('navigation',{name:'Moons navigation'}).getByRole('button',{name:'Store',exact:true}).click();
    await page.getByRole('button',{name:'Subscribe to Website Builder',exact:true}).click();
    await expect(page.getByRole('status').filter({hasText:'Website Builder subscribed successfully'})).toBeVisible();
    await expect(page.getByRole('link',{name:'Open Website Builder',exact:true})).toBeVisible();
    await page.reload();
    await expect(page.getByRole('link',{name:'Open Website Builder',exact:true})).toBeVisible();
    await page.goBack();
    await expect(page.getByRole('heading',{name:'Store',exact:true,level:2})).toBeVisible();
    await page.getByRole('navigation',{name:'Moons navigation'}).getByRole('button',{name:'Integrations',exact:true}).click();
    await expect(page.getByText('No integrations enabled yet')).toBeVisible();
    await expect(page.locator('.integration-foodpanda')).toHaveCount(0);
    await page.goBack();
    await expect(page.getByRole('heading',{name:'Store',exact:true,level:2})).toBeVisible();
    await page.getByRole('navigation',{name:'Moons navigation'}).getByRole('button',{name:'Discover',exact:true}).click();
    await expect(page.locator('.market-hero')).toBeVisible();
    await page.goto(origin+'/app/moons?tab=store');
    await expect(page.getByRole('heading',{name:'FBR',exact:true})).toBeVisible();
    await expect(page.getByRole('heading',{name:'WhatsApp',exact:true})).toBeVisible();
    await expect(page.locator('.integration-foodpanda img')).toHaveAttribute('src','/api/test-panda.svg');
    await page.locator('.integration-cards').screenshot({path:path.join(process.env.TEMP,'rms-integration-cards-desktop.png')});
    await page.getByRole('button',{name:/Foodpanda.*Enable/}).click();
    await page.getByRole('button',{name:'Enable Foodpanda',exact:true}).click();
    await expect(page).toHaveURL(/\/app\/integrations\/foodpanda$/);
    await expect(page.getByText('Accepting Foodpanda orders',{exact:true})).toBeVisible();
    await expect(page.getByText('#101',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Collapse Moons sidebar'}).click();
    await expect(page.getByRole('button',{name:'Expand Moons sidebar'})).toBeVisible();
    await page.getByRole('button',{name:'Expand Moons sidebar'}).click();
    await page.getByRole('button',{name:'Use dark theme'}).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.getByRole('button',{name:'Stop new orders'}).click();
    await expect(page.getByText('Foodpanda ordering stopped',{exact:true})).toBeVisible();
    await expect(page.getByText('#101',{exact:true})).toBeVisible();
    await page.screenshot({path:path.join(process.env.TEMP,'rms-foodpanda-desktop.png'),fullPage:true});
    await page.goto(origin+'/app/moons?tab=integrations');
    await expect(page.getByRole('button',{name:/Foodpanda.*Open/})).toBeVisible();
    await expect(page.getByRole('heading',{name:'FBR',exact:true})).toHaveCount(0);
    await expect(page.getByRole('heading',{name:'WhatsApp',exact:true})).toHaveCount(0);
    await page.setViewportSize({width:390,height:844});
    await page.locator('.integration-cards').screenshot({path:path.join(process.env.TEMP,'rms-integration-cards-mobile.png')});
    await page.setViewportSize({width:1440,height:1000});
    await page.getByRole('button',{name:/Foodpanda.*Open/}).click();
    await expect(page.getByText('#101',{exact:true})).toBeVisible();
    await expect(page.getByText('Foodpanda ordering stopped',{exact:true})).toBeVisible();
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Open navigation'}).click();
    await expect(page.getByRole('navigation',{name:'Foodpanda workspace'})).toBeVisible();
    await page.getByRole('button',{name:'Close navigation',exact:true}).last().click();
    await page.screenshot({path:path.join(process.env.TEMP,'rms-foodpanda-mobile.png'),fullPage:true});
    await page.goto(origin+'/app/moons');
    await expect(page.locator('.market-hero')).toBeVisible();
    await page.screenshot({path:path.join(process.env.TEMP,'rms-moons-hero-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Open navigation'}).click();
    await page.getByRole('navigation',{name:'Moons navigation'}).getByRole('button',{name:'Integrations',exact:true}).click();
    await expect(page.locator('.integration-cards')).toBeVisible();
    await expect(page.locator('.market-hero')).toHaveCount(0);
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(origin+'/app/pos');
    await expect(page.getByRole('button',{name:'Delivery',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'Foodpanda',exact:true})).toHaveCount(0);
    enabled=true;
    await page.reload();
    await page.getByRole('button',{name:'Foodpanda',exact:true}).click();
    await expect(page.getByText('Customer details, delivery and riders are handled by Foodpanda.')).toBeVisible();
    await expect(page.getByRole('button',{name:'Customer details',exact:true})).toHaveCount(0);
    await expect(page.getByRole('spinbutton',{name:'Delivery service charge',exact:true})).toHaveCount(0);
    await expect(page.getByRole('combobox',{name:'Rider',exact:true})).toHaveCount(0);
    await page.getByRole('button',{name:'Delivery',exact:true}).click();
    await expect(page.getByRole('combobox',{name:'Rider',exact:true})).toBeVisible();
  } finally {
    await browser.close();
    await new Promise(resolve=>server.close(resolve));
  }
});
